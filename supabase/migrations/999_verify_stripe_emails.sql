-- Find unmatched emails (Stripe emails NOT in profiles table)
SELECT
  'UNMATCHED STRIPE EMAILS' AS result,
  COUNT(*) AS count
FROM stripe_emails_unmatched s
WHERE LOWER(TRIM(s.email)) NOT IN (
  SELECT LOWER(TRIM(email)) FROM profiles
);

-- List unmatched emails
SELECT
  s.email AS stripe_email_not_in_profiles
FROM stripe_emails_unmatched s
WHERE LOWER(TRIM(s.email)) NOT IN (
  SELECT LOWER(TRIM(email)) FROM profiles
)
ORDER BY s.email;

-- Summary: Total Stripe emails vs Matched vs Unmatched
SELECT
  (SELECT COUNT(*) FROM stripe_emails_unmatched) AS total_stripe_emails,
  (SELECT COUNT(DISTINCT s.email) FROM stripe_emails_unmatched s
   WHERE LOWER(TRIM(s.email)) IN (SELECT LOWER(TRIM(email)) FROM profiles)) AS matched_emails,
  (SELECT COUNT(DISTINCT s.email) FROM stripe_emails_unmatched s
   WHERE LOWER(TRIM(s.email)) NOT IN (SELECT LOWER(TRIM(email)) FROM profiles)) AS unmatched_emails;

COMMIT;
